// Seeds a demo catalog for Lorem Store from fixtures/demo-catalog.json: one manual supplier, every fixture product
// (about two thirds published) and their placeholder photos (fixtures/demo-photos) in the MEDIA R2 bucket.
// Local by default (wrangler's local D1/R2 state); it never touches Cloudflare unless --remote is passed.
//
// Usage: node tools/seed-demo.mjs [--local] [--persist-to <dir>] [--config <wrangler config>] [--bucket <name>] [--dry-run]
//        node tools/seed-demo.mjs --remote --config <generated config> [--bucket <name>]
//   --persist-to  same directory as `wrangler dev --persist-to` (default: wrangler's own .wrangler/state)
//   --config      wrangler config (default wrangler.jsonc); its MEDIA r2_buckets entry names the bucket
//   --bucket      R2 bucket name when the config has no MEDIA binding (default lorem-store-media)
//   --dry-run     write the SQL and print the commands without running them
// Apply migrations first (npx wrangler d1 migrations apply DB --local ...).
//
// Idempotent: fixed supplier, product and media IDs. A re-run refreshes only the supplier snapshot (source_json) of
// products that still exist and are not in Trash, exactly as a supplier import does; manager overrides (publication,
// price, category, brand, edits) are written only when the product is first created and are never overwritten.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { validateSource, slugFor } from '../apps/api/src/domain.js';
import { suggestClassification, getCategory } from '../packages/catalog/taxonomy.js';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
const flag = name => args.includes(name);
const option = (name, fallback) => { const i = args.indexOf(name); if (i < 0) return fallback; const v = args[i + 1]; if (!v || v.startsWith('--')) throw new Error(`${name} needs a value`); return v; };
const KNOWN = new Set(['--local', '--remote', '--dry-run', '--persist-to', '--config', '--bucket']);
for (const [i, a] of args.entries()) if (a.startsWith('--') && !KNOWN.has(a)) throw new Error(`Unknown option ${a}`); else if (!a.startsWith('--') && !['--persist-to', '--config', '--bucket'].includes(args[i - 1])) throw new Error(`Unexpected argument ${a}`);
if (flag('--remote') && flag('--local')) throw new Error('Pass either --local or --remote, not both');
const remote = flag('--remote'), dryRun = flag('--dry-run');
const persistTo = option('--persist-to', null), configPath = option('--config', 'wrangler.jsonc');
if (remote && persistTo) throw new Error('--persist-to applies to local state only');

// JSONC: drop comments outside strings, then trailing commas.
const jsonc = text => JSON.parse(text.replace(/("(?:\\.|[^"\\])*")|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (m, s) => s ?? '').replace(/,(\s*[}\]])/g, '$1'));
const config = jsonc(await readFile(new URL(configPath, `file://${ROOT}`), 'utf8'));
const mediaBinding = (config.r2_buckets ?? []).find(b => b.binding === 'MEDIA');
const bucket = option('--bucket', mediaBinding?.bucket_name ?? 'lorem-store-media');
if (!/^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/.test(bucket)) throw new Error('Invalid bucket name');
if (remote && !mediaBinding && !args.includes('--bucket')) throw new Error('--remote needs a config with a MEDIA R2 binding or an explicit --bucket');

const BRANDS = ['Lorem', 'Ipsum', 'Dolor', 'Sitamet', 'Consectetur', 'Adipisci', 'Elitwear', 'Sedcotto', 'Tempora', 'Magnaline'];
const SUPPLIER_ID = '0d3e5a1c-7b2f-4c6d-9e8a-10ae0de30001';
const uuid = seed => { const h = createHash('sha256').update(seed).digest('hex'); return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`; };
const q = v => v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;

const fixture = JSON.parse(await readFile(new URL('fixtures/demo-catalog.json', `file://${ROOT}`), 'utf8'));
const base = Date.parse('2026-11-01T09:00:00.000Z');
const sql = [`-- Generated by tools/seed-demo.mjs. Demo data only.`,
  `INSERT INTO suppliers(id,name,url,enabled,created_at,provider) VALUES(${q(SUPPLIER_ID)},'Lorem Store демо',${q(`manual:${SUPPLIER_ID}`)},1,${q(new Date(base).toISOString())},'manual') ON CONFLICT(id) DO NOTHING;`];
const photos = new Map();
let published = 0;
for (const [i, raw] of fixture.items.entries()) {
  const source = validateSource(raw), id = uuid(`lorem-store-demo/product/${source.externalId}`);
  const { categoryId } = suggestClassification(source);
  if (!getCategory(categoryId) || categoryId === 'unclassified') throw new Error(`${source.externalId}: title does not resolve to a storefront category`);
  const brand = BRANDS.find(b => source.title.includes(b)) ?? null;
  const isPublished = i % 3 !== 2; if (isPublished) published++;
  // Retail = cost + fixed markup (about 30%, rounded to 10 UAH), as a manager would set it.
  const overrides = { published: isPublished, markupType: 'fixed', markupValue: Math.round(source.costMinor * 0.3 / 1000) * 1000, categoryId, ...(brand ? { brand } : {}) };
  const at = new Date(base + i * 60000).toISOString();
  sql.push(`INSERT INTO products(id,supplier_id,external_id,source_json,overrides_json,slug,updated_at) VALUES(${[id, SUPPLIER_ID, source.externalId, JSON.stringify(source), JSON.stringify(overrides), slugFor(source, id), at].map(q).join(',')})
  ON CONFLICT(supplier_id,external_id) DO UPDATE SET source_json=excluded.source_json,updated_at=CASE WHEN products.source_json=excluded.source_json THEN products.updated_at ELSE excluded.updated_at END WHERE products.deleted_at IS NULL;`);
  for (const url of source.photos) {
    const key = url.slice('/media/'.length);
    if (!/^[a-f0-9-]+\.webp$/.test(key)) throw new Error(`${source.externalId}: photo ${url} is not a local demo key`);
    if (!photos.has(key)) photos.set(key, await readFile(new URL(`fixtures/demo-photos/${key}`, `file://${ROOT}`)).catch(() => { throw new Error(`Missing fixtures/demo-photos/${key}; run node tools/placeholder-assets.mjs`); }));
  }
}
// Track the uploads like the Worker's own uploads, so the media library shows them and cleanup sees them as referenced.
for (const [key, bytes] of photos) sql.push(`INSERT INTO media_objects(key,size,content_type,sha256,kind,created_at,scanned_at) VALUES(${[key, bytes.length, 'image/webp', createHash('sha256').update(bytes).digest('hex'), 'upload', new Date(base).toISOString(), new Date(base).toISOString()].map(q).join(',')}) ON CONFLICT(key) DO NOTHING;`);
// One system audit entry for the first seeding (fixed id, so re-runs add nothing).
sql.push(`INSERT INTO audit_events(id,actor,action,resource_id,created_at,actor_type,actor_role,details_json) VALUES(${[uuid('lorem-store-demo/audit'), 'seed-demo', 'supplier.import', SUPPLIER_ID, new Date().toISOString(), 'system', null, JSON.stringify({ tool: 'tools/seed-demo.mjs', products: fixture.items.length })].map(q).join(',')}) ON CONFLICT(id) DO NOTHING;`);

const tmpDir = `${ROOT}.wrangler/tmp/`;
await mkdir(tmpDir, { recursive: true });
const sqlFile = `${tmpDir}seed-demo.sql`;
await writeFile(sqlFile, sql.join('\n') + '\n');

const target = remote ? ['--remote'] : ['--local', ...(persistTo ? ['--persist-to', persistTo] : [])];
const common = ['-c', configPath, ...target];
function wrangler(argv) {
  const shown = `npx wrangler ${argv.join(' ')}`;
  if (dryRun) { console.log(shown); return; }
  const r = spawnSync('npx', ['wrangler', ...argv], { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' });
  if (r.status !== 0) { process.stderr.write(r.stdout + r.stderr); throw new Error(`Failed: ${shown}`); }
}
console.log(`Seeding ${remote ? 'REMOTE' : 'local'} D1 (${configPath}${persistTo ? `, ${persistTo}` : ''}): ${fixture.items.length} products, ${published} published, ${photos.size} photos -> R2 bucket ${bucket}`);
if (!mediaBinding) console.warn(`Warning: ${configPath} has no MEDIA R2 binding, so the Worker cannot serve /media/* photos. Add {"binding":"MEDIA","bucket_name":"${bucket}"} to r2_buckets or pass --config.`);
wrangler(['d1', 'execute', 'DB', ...common, '--file', sqlFile, ...(remote ? ['--yes'] : [])]);
let n = 0;
for (const key of photos.keys()) {
  wrangler(['r2', 'object', 'put', `${bucket}/${key}`, '--file', `fixtures/demo-photos/${key}`, '--content-type', 'image/webp', ...common]);
  if (!dryRun && ++n % 10 === 0) console.log(`  ${n}/${photos.size} photos`);
}
console.log(dryRun ? `Dry run: SQL written to ${sqlFile}` : 'Done. Start the Worker with the same config and persist directory, then open /.');
